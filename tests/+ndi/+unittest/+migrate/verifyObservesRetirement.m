function r = verifyObservesRetirement(testCase, result, label)
%VERIFYOBSERVESRETIREMENT The second pass's element subjects, counted, on a migrated corpus.
%
%   R = ndi.unittest.migrate.verifyObservesRetirement(TESTCASE, RESULT, LABEL)
%   reads RESULT.secondPass.observesRetirement (ndi.migrate.local) and prints
%   it, the denominators first. Decided by Jess Haley, 2026-11-26 [no observes
%   relation in v2] (did-schema did_v2_standing_wiring_plan.md): v2 has no
%   `observes` relation; NDI's second pass reads each element's v1
%   `subject_id` directly, and the animal is the `entity_id` of the
%   observations and manipulations made with the element, or, where none
%   names it, is carried as the element's subject ([one-field carry in the
%   migration report], Jess Haley, 2026-11-19). It verifies that the step ran
%   (no step error, a report), that every converted element with a v1 subject
%   is named by a statement or carried under one reason, that no `observes`
%   relation is left in the batch (every one pass 1 wrote is removed), and
%   that every subject carried is a carried field of the run's migration
%   report. How many are carried is the calling test's to state. Whether the
%   carried elements still read their subject is
%   ndi.unittest.migrate.verifyCarriedSubjects's, and
%   ndi.unittest.migrate.corpusObjectEquivalence's (elements and probes:
%   subject, direct).
%
%   Until that decision this verified the `observes` relations retired and
%   kept ([observes retires in the second pass]); a kept relation is now a
%   failure.

r = result.secondPass.observesRetirement;
if isfield(result, 'secondPassErrors') && isstruct(result.secondPassErrors) ...
        && isfield(result.secondPassErrors, 'steps') && ~isempty(result.secondPassErrors.steps)
    steps = {result.secondPassErrors.steps.step};
    testCase.verifyFalse(any(strcmp(steps, 'observesRetirementFailed')), ...
        'the element subjects step threw');
end
testCase.assertTrue(isstruct(r) && isfield(r, 'elements_with_v1_subject'), ...
    'the second pass carries no element subjects report (the step did not run)');
fprintf(['\n  ELEMENT SUBJECTS (%s): %d document(s) inspected, %d v1 element(s) with a ' ...
    'subject (%d converted, %d carried as v1), %d presentation manipulation(s) naming %d ' ...
    'instrument(s), %d bath manipulation(s) naming %d instrument(s), %d other ' ...
    'manipulation(s), %d observation(s) with an instrument (%d attributed through the ' ...
    'v1 subject)\n' ...
    '    named by a statement: an observation %d, presentations %d, baths %d, other ' ...
    'manipulations %d\n' ...
    '    carried %d (several entities %d, other entities %d, no statement %d; recorded %d); ' ...
    'no carry API %d\n' ...
    '    pass-1 `observes` relations %d: removed %d (from the batch %d), kept %d ' ...
    '(no v1 subject %d)\n'], label, ...
    r.documents_inspected, r.elements_with_v1_subject, r.elements_converted, ...
    r.elements_not_converted, r.presentation_manipulations, ...
    r.presentation_instruments, r.bath_manipulations, r.bath_instruments, ...
    r.other_manipulations, r.observations_with_instrument, ...
    r.observations_attributed_via_subject, ...
    r.named_by_observation, r.named_by_presentation, r.named_by_bath, ...
    r.named_by_other_manipulation, r.carried, r.carried_several_entities, ...
    r.carried_other_entity, r.carried_no_statement, r.carried_recorded, ...
    r.kept_no_carry_api, r.observes_seen, r.observes_removed, r.removed, ...
    r.observes_kept, r.observes_without_v1_subject);
testCase.verifyGreaterThan(r.documents_inspected, 0, 'the step read no document (nothing measured)');
testCase.verifyEqual(r.elements_converted + r.elements_not_converted, ...
    r.elements_with_v1_subject, 'a v1 element with a subject was neither converted nor carried as v1');
testCase.verifyEqual(r.named_by_observation + r.named_by_presentation + r.named_by_bath + ...
    r.named_by_other_manipulation + r.carried + r.kept_no_carry_api, r.elements_converted, ...
    'a converted element was neither named by a statement nor carried');
testCase.verifyEqual(r.carried, ...
    r.carried_several_entities + r.carried_other_entity + r.carried_no_statement, ...
    'the carried elements do not add up by reason');
testCase.verifyEqual(r.kept_no_carry_api, 0, ...
    'a subject that needed a carry was not carried (no carried-field API)');
% [no observes relation in v2]: no `observes` relation is left
testCase.verifyEqual(r.observes_removed + r.observes_kept, r.observes_seen, ...
    'a pass-1 `observes` relation was neither removed nor kept');
testCase.verifyEqual(r.observes_kept, 0, 'an `observes` relation is left in the batch');
testCase.verifyEqual(r.removed, r.observes_removed, ...
    'the step removed a different number of relations than it decided to');
% [one-field carry in the migration report]: every subject carried is in the
% run's migration report, one carried field per element (carry-172)
testCase.verifyEqual(r.carried_recorded, r.carried, ...
    'an element whose subject is carried has no carried field recorded');
if isfield(result, 'migrationReport') && isstruct(result.migrationReport) ...
        && ~isempty(result.migrationReport) && isfield(result.migrationReport, 'counts')
    n = 0;
    for k = 1:numel(result.migrationReport)
        c = result.migrationReport(k).counts;
        if isfield(c, 'carried_fields')
            n = n + double(c.carried_fields);
        end
    end
    fprintf('    migration report: %d carried field(s)\n', n);
    testCase.verifyGreaterThanOrEqual(n, r.carried, ...
        'the migration report holds fewer carried fields than the subjects carried');
end
end
