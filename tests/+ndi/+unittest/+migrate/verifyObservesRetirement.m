function r = verifyObservesRetirement(testCase, result, label)
%VERIFYOBSERVESRETIREMENT The second pass's `observes` retirement, counted, on a migrated corpus.
%
%   R = ndi.unittest.migrate.verifyObservesRetirement(TESTCASE, RESULT, LABEL)
%   reads RESULT.secondPass.observesRetirement (ndi.migrate.local) and prints
%   it, the denominators first: Decided by Jess Haley, 2026-11-17
%   [observes retires in the second pass] (did-schema
%   did_v2_go_forward_class_audit.md), NDI's second pass retires a
%   stimulator's `observes` relation where a converted stimulus presentation
%   names the same device as instrument and the same animal as entity. It
%   verifies that the step ran (no step error, a report), that every
%   relation read is retired or kept under one reason, and that every
%   relation it retired was removed from the batch, and that every subject it
%   carried ([one-field carry in the migration report], Jess Haley,
%   2026-11-19) is a carried field of the run's migration report. How many
%   retire is the
%   calling test's to state. Whether the retired stimulators still read
%   their subject is ndi.unittest.migrate.corpusObjectEquivalence's (elements
%   and probes: subject, direct).

r = result.secondPass.observesRetirement;
if isfield(result, 'secondPassErrors') && isstruct(result.secondPassErrors) ...
        && isfield(result.secondPassErrors, 'steps') && ~isempty(result.secondPassErrors.steps)
    steps = {result.secondPassErrors.steps.step};
    testCase.verifyFalse(any(strcmp(steps, 'observesRetirementFailed')), ...
        'the `observes` retirement step threw');
end
testCase.assertTrue(isstruct(r) && isfield(r, 'observes_seen'), ...
    'the second pass carries no observesRetirement report (the step did not run)');
fprintf(['\n  OBSERVES RETIREMENT (%s): %d document(s) inspected, %d `observes` relation(s), ' ...
    '%d presentation manipulation(s) naming %d instrument(s), %d bath manipulation(s) ' ...
    'naming %d instrument(s), %d other manipulation(s), %d observation(s) with an ' ...
    'instrument (%d attributed through `observes`)\n' ...
    '    retired %d (removed %d): by a presentation %d, by a bath %d, with the subject ' ...
    'carried %d (other entities named %d, no statement %d; recorded %d)\n' ...
    '    kept %d: several entities %d, another manipulation names the subject %d, ' ...
    'observations made with the device %d, not a converted entity %d, no carry API %d, ' ...
    'several parents %d, incomplete %d\n'], label, ...
    r.documents_inspected, r.observes_seen, r.presentation_manipulations, ...
    r.presentation_instruments, r.bath_manipulations, r.bath_instruments, ...
    r.other_manipulations, r.observations_with_instrument, ...
    r.observations_attributed_via_observes, ...
    r.observes_retired, r.removed, r.retired_by_presentation, r.retired_by_bath, ...
    r.retired_carried, r.carried_other_entity, r.carried_no_statement, r.carried_recorded, ...
    r.observes_kept, r.kept_several_entities, r.kept_other_manipulation, ...
    r.kept_observation, r.kept_child_not_converted, r.kept_no_carry_api, ...
    r.kept_several_observes, r.kept_incomplete);
testCase.verifyGreaterThan(r.documents_inspected, 0, 'the step read no document (nothing measured)');
testCase.verifyEqual(r.observes_retired + r.observes_kept, r.observes_seen, ...
    'a relation read was neither retired nor kept');
testCase.verifyEqual(r.removed, r.observes_retired, ...
    'the step removed a different number of relations than it retired');
testCase.verifyEqual(r.observes_retired, ...
    r.retired_by_presentation + r.retired_by_bath + r.retired_carried, ...
    'the retired relations do not add up by reason');
% [one-field carry in the migration report]: every subject carried is in the
% run's migration report, one carried field per element (carry-172)
testCase.verifyEqual(r.carried_recorded, r.retired_carried, ...
    'a relation retired with its subject carried has no carried field recorded');
if isfield(result, 'migrationReport') && isstruct(result.migrationReport) ...
        && ~isempty(result.migrationReport) && isfield(result.migrationReport, 'counts')
    n = 0;
    for k = 1:numel(result.migrationReport)
        c = result.migrationReport(k).counts;
        if isfield(c, 'carried_fields')
            n = n + double(c.carried_fields);
        end
    end
    fprintf('    migration report: %d carried field(s)\n', n);
    testCase.verifyGreaterThanOrEqual(n, r.retired_carried, ...
        'the migration report holds fewer carried fields than the subjects carried');
end
end
